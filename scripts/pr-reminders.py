#!/usr/bin/env python3
"""Remind external contributors about unsigned CLAs and open CodeRabbit comments.

Runs from .github/workflows/pr-reminders.yml. Talks to GitHub only through
`gh api`, so it works locally with your own `gh` login and in Actions with
GH_TOKEN. Nothing is written unless --live is passed.

A PR gets a reminder when either holds:
  - `license/cla` is not SUCCESS and the PR is at least CLA_DAYS old.
  - A CodeRabbit thread is unresolved, not outdated, and has no reply from the
    PR author, and the author has neither pushed nor commented in the CODERABBIT_DAYS
    since CodeRabbit's last review.

Each reminder carries MARKER. A PR gets at most MAX_REMINDERS of them, at least
REMIND_INTERVAL_DAYS apart; after that it is labeled STALE_LABEL instead.
"""

import argparse
import json
import os
import re
import subprocess
import sys
from datetime import datetime, timedelta, timezone

CLA_DAYS = 3
CODERABBIT_DAYS = 7
REMIND_INTERVAL_DAYS = 14
MAX_REMINDERS = 2

CLA_CONTEXT = "license/cla"
CODERABBIT = "coderabbitai"
WORKFLOW_BOT = "github-actions"
MARKER = "<!-- odl-pr-reminder -->"
# Footer of the reminders posted by hand before this workflow; they count too.
MANUAL_FOOTER = "This comment was generated by AI and may contain mistakes."
CLA_LABEL = "needs-cla"
STALE_LABEL = "stale"
# Created on the first live run if missing: (color, description).
LABELS = {
    CLA_LABEL: ("fbca04", "The author has not signed the CLA yet"),
    STALE_LABEL: ("ededed", "No response after the maximum number of reminders"),
}
SKIP_ASSOCIATIONS = {"OWNER", "MEMBER", "COLLABORATOR"}
MAINTAINER_PERMISSIONS = {"admin", "maintain", "write"}

FOOTER = "---\n<sub>🤖 This is an automated reminder and may contain mistakes.</sub>"
CLA_TEXT = (
    "Please sign our Contributor License Agreement (CLA) via the link in the "
    "`license/cla` check (or the CLA assistant comment above). The check will "
    "update automatically once it's signed. If this reminder seems mistaken "
    "(e.g., you've already signed), please let us know and we'll look into it."
)
CODERABBIT_TEXT = (
    "Could you either push a fix or reply in the thread? CodeRabbit is an "
    "automated reviewer and can be wrong. If you think a suggestion doesn't "
    "apply, just reply in the thread with your reasoning. That's a perfectly "
    "fine way to resolve it."
)

QUERY = """
query($owner: String!, $name: String!, $cursor: String) {
  repository(owner: $owner, name: $name) {
    pullRequests(states: OPEN, first: 20, after: $cursor) {
      pageInfo { hasNextPage endCursor }
      nodes {
        number isDraft createdAt authorAssociation
        author { __typename login }
        labels(first: 50) { nodes { name } }
        commits(last: 1) { nodes { commit {
          oid
          status { contexts { context state } }
        } } }
        reviewThreads(first: 100) { nodes {
          isResolved isOutdated
          comments(first: 50) { nodes { url createdAt author { login } body } }
        } }
        reviews(last: 50) { nodes { submittedAt author { login } commit { oid } } }
        comments(last: 100) { totalCount nodes { createdAt body authorAssociation author { login } } }
      }
    }
  }
}
"""


def run_gh(*args, input=None):
    """Run gh. Return the error text, or None on success."""
    result = subprocess.run(["gh", *args], input=input, capture_output=True, text=True)
    return f"gh {' '.join(args[:2])} failed: {result.stderr.strip()}" if result.returncode else None


def gh(*args, input=None):
    result = subprocess.run(["gh", *args], input=input, capture_output=True, text=True)
    if result.returncode != 0:
        sys.exit(f"gh {' '.join(args[:2])} failed: {result.stderr.strip()}")
    return result.stdout


def fetch_open_prs(repo):
    owner, name = repo.split("/")
    prs, cursor = [], None
    while True:
        args = ["api", "graphql", "-f", f"query={QUERY}", "-F", f"owner={owner}", "-F", f"name={name}"]
        if cursor:
            args += ["-F", f"cursor={cursor}"]
        page = json.loads(gh(*args))["data"]["repository"]["pullRequests"]
        prs += page["nodes"]
        if not page["pageInfo"]["hasNextPage"]:
            break
        cursor = page["pageInfo"]["endCursor"]
    # The query keeps only the last 100 comments; older reminders must count too.
    for pr in prs:
        if pr["comments"]["totalCount"] > len(pr["comments"]["nodes"]):
            pr["comments"]["nodes"] = fetch_all_comments(repo, pr["number"])
    return prs


def fetch_all_comments(repo, number):
    jq = (
        '.[] | {createdAt: .created_at, body, authorAssociation: .author_association,'
        ' author: {login: (.user.login | sub("\\\\[bot\\\\]$"; ""))}}'
    )
    out = gh("api", "--paginate", f"repos/{repo}/issues/{number}/comments", "--jq", jq)
    return [json.loads(line) for line in out.splitlines() if line]


def ts(value):
    return datetime.fromisoformat(value.replace("Z", "+00:00"))


def login(node):
    return (node.get("author") or {}).get("login") or ""


def comment_title(body):
    # CodeRabbit puts the finding in the first line that is bold as a whole. The
    # category line before it can be bold in parts ("**🎯 …** | **🟠 Major**").
    match = re.search(r"^\*\*([^*\n]+)\*\*\s*$", body, re.MULTILINE)
    return match.group(1).rstrip(".")[:120] if match else "CodeRabbit comment"


def cla_state(pr):
    """The `license/cla` state, or None if the check is missing.

    CLA assistant reports an unsigned CLA as PENDING, so any state other than
    SUCCESS means the CLA is not signed yet.
    """
    status = pr["commits"]["nodes"][0]["commit"]["status"] or {"contexts": []}
    return next((c["state"] for c in status["contexts"] if c["context"] == CLA_CONTEXT), None)


def open_coderabbit_threads(pr, now):
    author = login(pr)
    reviews = [r for r in pr["reviews"]["nodes"] if login(r) == CODERABBIT and r["submittedAt"]]
    if not reviews:
        return []
    last = max(reviews, key=lambda r: ts(r["submittedAt"]))
    last_review = ts(last["submittedAt"])
    if now - last_review < timedelta(days=CODERABBIT_DAYS):
        return []
    # A push or a conversation comment after the review counts as a response.
    # Compare commits, not commit dates: a pushed commit can be older than the review.
    if (last["commit"] or {}).get("oid") != pr["commits"]["nodes"][0]["commit"]["oid"]:
        return []
    if any(login(c) == author and ts(c["createdAt"]) > last_review for c in pr["comments"]["nodes"]):
        return []
    threads = []
    for thread in pr["reviewThreads"]["nodes"]:
        comments = thread["comments"]["nodes"]
        if thread["isResolved"] or thread["isOutdated"] or not comments:
            continue
        if login(comments[0]) != CODERABBIT or any(login(c) == author for c in comments):
            continue
        threads.append((comment_title(comments[0]["body"]), comments[0]["url"]))
    return threads


def build_body(author, cla, threads):
    parts = [f"Hi @{author}, thanks for your contribution!"]
    if cla and threads:
        parts.append("Two things are needed before we can move forward:")
    if cla:
        parts.append(("**1. CLA:** " if threads else "Before we can review and merge this PR, we need a signed CLA. ") + CLA_TEXT)
    if threads:
        heading = "**2. Open CodeRabbit comments:**" if cla else "CodeRabbit left review comments that are still open:"
        parts.append(heading + "\n" + "\n".join(f"- [{title}]({url})" for title, url in threads))
        parts.append(CODERABBIT_TEXT)
    parts.append(FOOTER + "\n" + MARKER)
    return "\n\n".join(parts) + "\n"


def fetch_maintainers(repo, prs):
    """Logins with write access among the PR authors and the reminder authors.

    authorAssociation is not enough: a token that cannot see private org
    membership, like GITHUB_TOKEN, reports a private member as CONTRIBUTOR.
    """
    logins = {login(pr) for pr in prs if (pr.get("author") or {}).get("__typename") == "User"}
    logins |= {login(c) for pr in prs for c in pr["comments"]["nodes"] if MARKER in c["body"] or MANUAL_FOOTER in c["body"]}
    logins -= {"", WORKFLOW_BOT}
    return {name for name in logins if permission(repo, name) in MAINTAINER_PERMISSIONS}


def permission(repo, name):
    result = subprocess.run(
        ["gh", "api", f"repos/{repo}/collaborators/{name}/permission", "--jq", ".permission"],
        capture_output=True, text=True,
    )
    # An app login such as Copilot is "not a user" (404): it has no permission.
    if result.returncode != 0 and "HTTP 404" in result.stderr:
        return "none"
    if result.returncode != 0:
        sys.exit(f"gh api permission failed for {name}: {result.stderr.strip()}")
    return result.stdout.strip()


def plan(prs, now, maintainers=frozenset()):
    actions = []
    for pr in prs:
        author_node = pr.get("author") or {}
        if pr["isDraft"] or author_node.get("__typename") == "Bot" or is_maintainer(pr, maintainers):
            continue
        labels = {l["name"] for l in pr["labels"]["nodes"]}
        state = cla_state(pr)
        cla = state not in (None, "SUCCESS") and now - ts(pr["createdAt"]) >= timedelta(days=CLA_DAYS)
        # Only a passing check clears the label; a missing check changes nothing.
        if state == "SUCCESS" and CLA_LABEL in labels:
            actions.append((pr["number"], "unlabel", CLA_LABEL))
        if cla and CLA_LABEL not in labels:
            actions.append((pr["number"], "label", CLA_LABEL))
        threads = open_coderabbit_threads(pr, now)
        if not cla and not threads:
            continue
        sent = sorted(ts(c["createdAt"]) for c in pr["comments"]["nodes"] if is_reminder(c, maintainers))
        if len(sent) >= MAX_REMINDERS:
            if STALE_LABEL not in labels:
                actions.append((pr["number"], "label", STALE_LABEL))
            continue
        if sent and now - sent[-1] < timedelta(days=REMIND_INTERVAL_DAYS):
            continue
        actions.append((pr["number"], "comment", build_body(login(pr), cla, threads)))
    return actions


def is_maintainer(node, maintainers):
    return login(node) in maintainers or node.get("authorAssociation") in SKIP_ASSOCIATIONS


def is_reminder(comment, maintainers):
    # Anyone can paste the marker, so count it only from this workflow or a maintainer.
    trusted = login(comment) == WORKFLOW_BOT or is_maintainer(comment, maintainers)
    return trusted and (MARKER in comment["body"] or MANUAL_FOOTER in comment["body"])


def ensure_labels(repo, actions):
    existing = set(gh("label", "list", "-R", repo, "--limit", "1000", "--json", "name", "--jq", ".[].name").split())
    for name in sorted({value for _, kind, value in actions if kind == "label"} - existing):
        color, description = LABELS[name]
        gh("label", "create", name, "-R", repo, "--color", color, "--description", description)


def apply(repo, number, kind, value):
    if kind == "comment":
        return run_gh("pr", "comment", str(number), "-R", repo, "--body-file", "-", input=value)
    if kind == "label":
        return run_gh("pr", "edit", str(number), "-R", repo, "--add-label", value)
    return run_gh("pr", "edit", str(number), "-R", repo, "--remove-label", value)


def summarize(actions, live):
    lines = [f"## PR reminders ({'live' if live else 'dry run'})", ""]
    if not actions:
        lines.append("Nothing to do.")
    for number, kind, value in actions:
        if kind == "comment":
            lines += [f"<details><summary>#{number}: comment</summary>", "", value, "</details>"]
        else:
            lines.append(f"- #{number}: {kind} `{value}`")
    text = "\n".join(lines) + "\n"
    print(text)
    if os.environ.get("GITHUB_STEP_SUMMARY"):
        with open(os.environ["GITHUB_STEP_SUMMARY"], "a") as f:
            f.write(text)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--repo", default=os.environ.get("GITHUB_REPOSITORY"), required=not os.environ.get("GITHUB_REPOSITORY"))
    parser.add_argument("--live", action="store_true", help="post comments and edit labels (default: dry run)")
    args = parser.parse_args()

    prs = fetch_open_prs(args.repo)
    actions = plan(prs, datetime.now(timezone.utc), fetch_maintainers(args.repo, prs))
    summarize(actions, args.live)
    if not args.live:
        return
    ensure_labels(args.repo, actions)
    # One failed action must not block the reminders for the other PRs.
    errors = [f"#{a[0]} {a[1]}: {e}" for a in actions if (e := apply(args.repo, *a))]
    if errors:
        sys.exit("\n".join(errors))


if __name__ == "__main__":
    main()
