# Correlates every log line emitted while serving one request. Python's logging
# has no equivalent of Java's MDC, so the id travels in a context variable and
# `_RequestIdFilter` copies it onto each record for the formatter to render.
_request_id: contextvars.ContextVar[str] = contextvars.ContextVar(
    "request_id", default="-"
)


class _RequestIdFilter(logging.Filter):
    """Stamp each record with the request being served when it was emitted.

    Reaches docling's lines too, since they are logged on the thread running
    the conversion. Records from a thread docling started itself, and those
    emitted outside any request, carry "-": a context variable is not
    inherited by a bare `threading.Thread`, so the id genuinely is not known
    there rather than being omitted.
    """

    def filter(self, record: logging.LogRecord) -> bool:
        record.request_id = _request_id.get()
        return True


# A single format for our logger, docling's and uvicorn's. Before this, our
# lines came from `basicConfig` while uvicorn kept its own timestamp-less
# `levelprefix` format, so the two could not be read as one timeline -- the
# reason the #414 report could not be diagnosed from the log alone.
_LOG_FORMAT = "%(asctime)s.%(msecs)03d | %(levelname)-7s | %(request_id)-12s | %(message)s"
_LOG_FORMAT_DEBUG = (
    "%(asctime)s.%(msecs)03d | %(levelname)-7s | %(request_id)-12s | "
    "%(threadName)-14s | %(name)s | %(message)s"
)
_LOG_DATEFMT = "%Y-%m-%d %H:%M:%S"

# Marks the handler `configure_logging` owns, so that repeat calls replace that
# one and leave an embedding application's handlers alone.
_CONSOLE_HANDLER = "odl_console"

# Ids only have to stay distinct among the requests visible together in a log.
# Three bytes collide at about 3% over a thousand requests, which is frequent
# enough to mislead someone correlating lines; six makes it negligible.
_REQUEST_ID_BYTES = 6


class _IndentTracebacks(logging.Formatter):
    """Formatter that keeps a traceback from looking like separate records.

    `exc_info` text is appended after the formatted message, and an exception
    raised over caller-supplied data carries that data in its message -- a
    parser error quoting PDF object bytes, for instance. A newline in there
    ends the physical line, and what follows can be shaped exactly like one of
    this module's own records, so a failed request could be made to read as a
    successful one.

    Each continuation line is prefixed so it cannot be mistaken for a record
    of its own. The traceback's own structure is left intact, since that is
    what makes it worth logging.
    """

    _CONTINUATION = "    | "

    def format(self, record: logging.LogRecord) -> str:
        # `logging.Formatter.format` caches the traceback it renders on the
        # record, and every later formatter reuses that text. A handler an
        # embedding application installed formats the same record first, so
        # the cache would hold an unprefixed traceback by the time this
        # formatter runs -- and the prefixing below would never happen.
        # Cleared so the prefix is applied to whatever this handler writes.
        cached, record.exc_text = record.exc_text, None
        try:
            return super().format(record)
        finally:
            # Put it back: the next handler is entitled to its own rendering,
            # and leaving None would make it re-render rather than reuse.
            record.exc_text = cached

    def formatException(self, ei: Any) -> str:
        text = super().formatException(ei)
        return "\n".join(self._CONTINUATION + line for line in text.splitlines())


def configure_logging(level: str = "info") -> None:
    """Point our logger, docling's and uvicorn's at one console handler.

    `--log-level` previously reached only `uvicorn.run()`, while this module
    pinned the root logger to INFO at import time, so the flag had no effect on
    our own or docling's output. Setting the levels here makes it real.

    docling shares our level so that its startup lines -- which model is being
    fetched, which OCR engine was chosen -- land in the same timeline as ours.
    Timing the load is this server's own job: docling times downloads, not the
    weight loading that dominates a warm cache.

    Built by hand rather than with `dictConfig`, which is destructive: a
    non-incremental config clears the root logger's handlers and calls
    `close()` on each one. Handlers belonging to an embedding application
    survived that only as objects -- a `FileHandler` reopened in "w" mode or a
    handler that latches on `close()` would stop recording. Only the handler
    this function owns is replaced.
    """
    level_name = level.upper()
    level_value = getattr(logging, level_name, logging.INFO)

    formatter = _IndentTracebacks(
        _LOG_FORMAT_DEBUG if level_name == "DEBUG" else _LOG_FORMAT,
        datefmt=_LOG_DATEFMT,
    )

    root = logging.getLogger()
    for handler in list(root.handlers):
        if getattr(handler, "name", None) == _CONSOLE_HANDLER:
            root.removeHandler(handler)
            handler.close()

    console = logging.StreamHandler(stream=sys.stdout)
    console.name = _CONSOLE_HANDLER
    console.setFormatter(formatter)
    console.addFilter(_RequestIdFilter())
    root.addHandler(console)
    root.setLevel(level_value)

    for name, logger_level in (
        ("docling", level_value),
        # httpx logs a line per HTTP request at INFO, which during a model
        # fetch means one per HuggingFace metadata call. The others are
        # DEBUG-only today; pinned so that a future default cannot start
        # narrating our startup.
        ("httpx", logging.WARNING),
        ("httpcore", logging.WARNING),
        ("urllib3", logging.WARNING),
        ("filelock", logging.WARNING),
        ("uvicorn", level_value),
        ("uvicorn.error", level_value),
        # Our own per-request lines carry the caller, file, size, page count
        # and timings, so uvicorn's access line would only repeat the request
        # without the id that ties it to the rest.
        ("uvicorn.access", logging.WARNING),
    ):
        logger_obj = logging.getLogger(name)
        logger_obj.setLevel(logger_level)
        # uvicorn sets `propagate = False` on its loggers when it configures
        # logging; cleared so its lines reach our console in our format. Its
        # handlers need no removal -- `main()` passes `log_config=None`, so it
        # installs none -- and removing them wholesale would have detached a
        # handler an embedding application had attached here.
        logger_obj.propagate = True


# Not called at import: `basicConfig` used to be a documented no-op once the
# root logger had handlers, so importing this module could not disturb an
# embedding application's logging. dictConfig has no such courtesy -- it would
# reset the root level -- so the server configures logging in `main()` instead.
logger = logging.getLogger(__name__)

