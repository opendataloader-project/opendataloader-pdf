def _extract_failed_pages_from_errors(errors: list[str]) -> list[int]:
    """Extract failed page numbers from error messages.

    Docling error messages follow the pattern "Page N: <error>" (e.g.,
    "Page 26: std::bad_alloc") or, when no error description is available,
    a bare "Page N" with no colon. Even when docling includes failed pages
    in the pages dict as empty entries, the error messages reliably
    indicate which pages actually failed.

    Args:
        errors: List of error message strings.

    Returns:
        Sorted list of 1-indexed page numbers that failed.
    """
    failed = set()
    page_pattern = re.compile(r"^Page\s+(\d+)(?::|$)")
    for msg in errors:
        m = page_pattern.match(msg)
        if m:
            failed.add(int(m.group(1)))
    return sorted(failed)


def extract_timings(result: Any) -> dict[str, Any]:
    """Extract per-step pipeline timings from a Docling ConversionResult.

    Requires DOCLING_DEBUG_PROFILE_PIPELINE_TIMINGS=true (set at module level).
    Returns a dict keyed by step name (e.g. "layout", "ocr", "table_structure")
    with total_s, avg_s, and count for each step.
    """
    timings_out: dict[str, Any] = {}
    raw_timings = getattr(result, "timings", None)
    if not raw_timings:
        return timings_out
    unreadable: list[str] = []
    last_error: Exception | None = None
    for name, item in raw_timings.items():
        try:
            timings_out[name] = {
                "total_s": round(item.total(), 4),
                "avg_s": round(item.avg(), 4) if item.count > 0 else 0.0,
                "count": item.count,
            }
        except Exception as e:
            # Collected rather than logged here: a docling API change fails
            # every step, and one warning per step per request would bury the
            # lines someone is reading the log for.
            unreadable.append(name)
            last_error = e
    if unreadable:
        # Still said out loud once: silently dropping timings makes the
        # per-stage breakdown look absent instead of broken.
        logger.warning(
            "timings_unreadable %s",
            _pairs(
                failed=len(unreadable),
                total=len(raw_timings),
                steps=_bounded(",".join(unreadable)),
                error=_bounded(str(last_error), 500),
            ),
        )
    return timings_out


# The docling profiling keys worth a place on the completion line, mapped to
# shorter log keys. docling emits more than these -- layout_postprocess,
# reading_order, doc_assemble and others -- so the whitelist keeps the line
# short, and it also keeps a docling key from colliding with a fixed one:
# these are splatted as keyword arguments into `_pairs`, where a duplicate
# raises TypeError and costs the request its response.
_STAGE_LABELS = {
    "ocr": "ocr",
    "layout": "layout",
    "table_structure": "tables",
    "page_parse": "parse",
}

# Heartbeat spacing, widening as a conversion runs on: attentive while the
# operator is still deciding whether anything is wrong, sparse once the answer
# is "it is simply slow". A flat 15s spent 31 lines on an eight-minute
# conversion, which is 31 lines saying the same thing.
_PROGRESS_INTERVAL_S = 15.0
_PROGRESS_BACKOFF = (
    (60.0, 15.0),    # first minute: every 15s
    (300.0, 60.0),   # to five minutes: every minute
    (None, 120.0),   # beyond: every two minutes
)


# The two control characters worth reading back: a newline forges a new record
# and a carriage return overwrites the line already printed, so both are named
# rather than dropped. Every other non-printable becomes `_REPLACEMENT` -- an
# ANSI escape has no reading worth preserving.
_CONTROL_ESCAPES = {"\n": "\\n", "\r": "\\r"}

# Stands in for a character with no reading worth keeping. Deliberately ASCII:
# U+FFFD cannot be encoded on a cp949 or cp1252 console, and `logging` drops a
# record it cannot write -- so a filename holding one zero-width character
# would have erased its own log line on a Korean Windows console, turning this
# sanitizing into a way to go unlogged.
_REPLACEMENT = "?"


def _pairs(**fields: Any) -> str:
    """Render fields as logfmt, in the order given, skipping None.

    The lines this module emits are read two ways: by someone watching the
    console, and by grep or a log reader afterwards. logfmt serves both --
    `dur=34.5s` says what the number is without a legend, and `ocr=33.8s` can
    be extracted without a regex per line. A value holding a space or a quote
    is quoted, since an unquoted one would parse as two fields.
    """
    out = []
    for key, value in fields.items():
        if value is None:
            continue
        text = str(value)
        # Backslashes first, so that the escapes below are the only ones in
        # the output. Doubling afterwards would re-escape them, and `a\nb`
        # typed literally would render identically to a real newline -- the
        # distinction this escaping exists to preserve.
        text = text.replace("\\", "\\\\")
        # Quoting does not contain a newline: it still ends the physical line,
        # and the rest parses as a record of its own, which is how a
        # caller-supplied value forges log entries (CWE-117). So control
        # characters are rewritten, not merely wrapped in quotes.
        text = "".join(
            c if c.isprintable() or c == "\t" else _CONTROL_ESCAPES.get(c, _REPLACEMENT)
            for c in text
        )
        if text == "" or any(c in text for c in ' "=\t'):
            text = '"' + text.replace('"', '\\"') + '"'
        out.append(f"{key}={text}")
    return " ".join(out)


def _bounded(value: str, limit: int = 120) -> str:
    """Truncate a caller-supplied value to a length fit for one log line.

    Starlette caps a form field at 1MiB, so a malformed `page_ranges` could
    put a megabyte on one line and, repeated, flood the log that the rest of
    this module exists to keep readable. `%r` already neutralizes its
    contents; this bounds its size.
    """
    if len(value) <= limit:
        return value
    return value[:limit] + f"...({len(value)} chars)"


def _safe_log_name(raw: str | None, limit: int = 120) -> str:
    """Reduce an uploaded filename to one printable token safe to log.

    `os.path.basename` strips directories but not control characters. A
    filename holding a newline forges whole lines in this module's log format,
    and an ANSI escape runs when an operator views the log, so a log meant to
    settle what happened could instead be written by the caller.
    """
    name = os.path.basename(raw or "unnamed")
    name = "".join(c if c.isprintable() else _REPLACEMENT for c in name)
    if len(name) > limit:
        name = name[:limit] + "...(truncated)"
    return name or "unnamed"


def _stages_slowest_first(step_timings: dict[str, Any]) -> dict[str, str]:
    """Per-stage durations for the completion line, slowest first.

    #414 was a request whose cost was almost entirely OCR, reported in a fixed
    order that put layout ahead of it, so the number that explained the
    request was not the one the eye landed on.
    """
    # Guarded on the value, not just the key: `extract_timings` builds these
    # from docling's ProfilingItem, and a stage that reported nothing usable
    # would otherwise reach the format string as None and cost the request its
    # response over a log line.
    usable = {
        name: item["total_s"]
        for name, item in step_timings.items()
        if name in _STAGE_LABELS
        and isinstance(item, dict)
        and isinstance(item.get("total_s"), (int, float))
    }
    return {
        _STAGE_LABELS[name]: f"{total:.1f}s"
        for name, total in sorted(
            usable.items(), key=lambda kv: kv[1], reverse=True
        )
    }


def _converted_page_count(
    page_range: tuple[int, int] | None, total_pages: int | None
) -> int | None:
    """How many pages a request actually converted.

    docling reports the document's length, which is the answer only when the
    whole document was asked for. Returns None when neither bound is known.
    """
    if page_range is None:
        return total_pages
    start, end = page_range
    if total_pages is not None:
        end = min(end, total_pages)
        start = max(start, 1)
    return max(0, end - start + 1)


def _client_address(request: Any) -> str:
    """Who sent this request, for the log.

    The server binds 0.0.0.0 by default and has no authentication, so the
    caller's address is the only thing tying an upload to an origin. uvicorn's
    access log used to carry it; this server logs its own request lines
    instead, which left nothing recording the sender.
    """
    client = getattr(request, "client", None)
    if client is None or not getattr(client, "host", None):
        # Absent for a connection over a Unix socket, and in tests that build
        # a request without one.
        return "unknown"
    return client.host


def _probe_page_count(pdf_path: str) -> int | None:
    """Page count of an uploaded PDF, or None if it cannot be read.

    Uses pypdfium2, which docling already depends on. Failure is not an error
    here: a PDF too damaged to page-count may still convert, and the count is
    only used to annotate log lines.
    """
    try:
        import pypdfium2

        doc = pypdfium2.PdfDocument(pdf_path)
        try:
            return len(doc)
        finally:
            doc.close()
    except Exception as e:
        logger.debug("could not read page count from the upload: %s", e)
        return None


class _ConversionHeartbeat:
    """Report that a long conversion is still running, from a side thread.

    Per-page progress has no seam to read: docling keeps the finished-page
    tally in a local of its pipeline's `execute()`, and its per-stage page
    lines are DEBUG-only, below the level this server runs at. What an operator
    needs first is anyway the difference between "working" and "hung", which
    elapsed time answers honestly; the per-stage breakdown logged at the end
    says where the time actually went.

    Runs as a daemon so it can never hold up interpreter shutdown.
    """

    def __init__(self, file_name: str, page_count: int | None) -> None:
        self._file_name = file_name
        self._page_count = page_count
        self._stop = threading.Event()
        self._thread: threading.Thread | None = None
        # Inherit the request id so heartbeat lines carry the same tag.
        self._request_id = _request_id.get()

    def __enter__(self) -> "_ConversionHeartbeat":
        self._thread = threading.Thread(
            target=self._run, name="convert-heartbeat", daemon=True
        )
        self._thread.start()
        return self

    def __exit__(self, *exc: Any) -> None:
        self._stop.set()
        if self._thread is not None:
            self._thread.join(timeout=1.0)

    @staticmethod
    def _interval_at(elapsed: float) -> float:
        """Heartbeat spacing for a conversion that has run this long.

        A caller that shortens `_PROGRESS_INTERVAL_S` below the table's first
        step -- the tests, to avoid waiting out a real backoff -- gets that
        value at every stage instead.
        """
        if _PROGRESS_INTERVAL_S < _PROGRESS_BACKOFF[0][1]:
            return _PROGRESS_INTERVAL_S
        for until, interval in _PROGRESS_BACKOFF:
            if until is None or elapsed < until:
                return interval
        return _PROGRESS_BACKOFF[-1][1]

    def _run(self) -> None:
        token = _request_id.set(self._request_id)
        try:
            start = time.perf_counter()
            while not self._stop.wait(
                self._interval_at(time.perf_counter() - start)
            ):
                logger.info(
                    "converting %s",
                    _pairs(
                        file=self._file_name,
                        pages=self._page_count,
                        elapsed=f"{time.perf_counter() - start:.0f}s",
                    ),
                )
        finally:
            _request_id.reset(token)


def build_conversion_response(
    status_value: str,
    json_content: dict,
    processing_time: float,
    errors: list[str],
    requested_pages: tuple[int, int] | None,
    total_pages: int | None = None,
    timings: dict[str, Any] | None = None,
) -> dict:
    """Build a structured conversion response with status and failed page info.

    When Docling encounters errors (e.g., std::bad_alloc in PDF preprocessing),
    it may still include failed pages as empty entries in the pages dict.
    This function combines two strategies to detect failed pages:
    1. Parse page numbers from error messages ("Page N: <error>")
    2. Detect pages missing from the output pages dict (gap detection)
    Both results are merged (union) since each catches a different failure mode.

    Args:
        status_value: Docling ConversionStatus value as string (e.g., "success", "partial_success").
        json_content: The exported document dict from Docling.
        processing_time: Time taken for conversion in seconds.
        errors: List of error message strings from Docling.
        requested_pages: Tuple of (start, end) 1-indexed page range, or None for all pages.
        total_pages: Total page count of the input document (from Docling InputDocument).
                     Used to detect boundary page failures when requested_pages is None.

    Returns:
        Response dict with status, document, errors, failed_pages, and processing_time.
    """
    failed_pages: list[int] = []

    if status_value == "partial_success":
        # Strategy 1: Extract failed pages from error messages (reliable —
        # docling may include failed pages as empty entries in the pages dict,
        # making gap detection ineffective)
        error_failed = set(_extract_failed_pages_from_errors(errors))

        # Strategy 2: Detect pages missing from the pages dict (catches
        # failures that don't produce "Page N:" error messages)
        gap_failed: set[int] = set()
        pages_dict = json_content.get("pages", {})
        present_pages = set()
        for k in pages_dict.keys():
            try:
                present_pages.add(int(k))
            except (ValueError, TypeError):
                # Bounded like the other values this module echoes. docling
                # builds these keys, so an enormous one is a bug rather than
                # an attack, but a log line is capped either way.
                logger.warning(
                    "unexpected_page_key %s",
                    _pairs(key=_bounded(repr(k))),
                )

        if requested_pages:
            expected_pages = set(range(requested_pages[0], requested_pages[1] + 1))
        elif total_pages is not None:
            expected_pages = set(range(1, total_pages + 1))
        elif present_pages:
            logger.warning(
                "No page range or total_pages available; boundary page failures cannot be detected"
            )
            expected_pages = set(range(min(present_pages), max(present_pages) + 1))
        else:
            expected_pages = set()

        gap_failed = expected_pages - present_pages

        # Union: each strategy catches a different failure mode
        failed_pages = sorted(error_failed | gap_failed)

    response: dict[str, Any] = {
        "status": status_value,
        "document": {
            "json_content": json_content,
        },
        "processing_time": processing_time,
        "errors": errors,
        "failed_pages": failed_pages,
    }

    if timings:
        response["timings"] = timings

    return response


def sanitize_unicode(data: Any) -> Any:
    """Recursively replace lone surrogates and null characters with U+FFFD.

    Docling OCR can produce lone surrogates (U+D800-U+DFFF) and null characters
    from PDFs with malformed font encodings. These pass through json.dumps(ensure_ascii=False)
    but fail on .encode('utf-8') in Starlette's JSONResponse.render(), causing
    UnicodeEncodeError and a 500 response.

    This mirrors the Java-side TextProcessor.replaceUndefinedCharacters().

    Args:
        data: Arbitrary data structure (dict, list, str, or primitive) from
              Docling's export_to_dict() output.

    Returns:
        The same structure with problematic characters replaced by U+FFFD.
    """
    if isinstance(data, str):
        return _INVALID_UNICODE_RE.sub("\ufffd", data)
    if isinstance(data, dict):
        return {k: sanitize_unicode(v) for k, v in data.items()}
    if isinstance(data, list):
        return [sanitize_unicode(item) for item in data]
    return data


def _get_loop_setting() -> str:
    """Return the uvicorn event loop setting appropriate for the current platform.

    uvloop is not supported on Windows, so we force 'asyncio' there.
    On other platforms, 'auto' lets uvicorn use uvloop if available.
    """
    if sys.platform == "win32":
        return "asyncio"
    return "auto"


